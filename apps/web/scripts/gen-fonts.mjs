// Writes src/fonts.css (and prints the packages to depend on) from the fonts the installed turbothemes styles ask for, so every style
// works offline. Run after updating turbothemes:  node scripts/gen-fonts.mjs   then   pnpm add <packages it prints>
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const themes = JSON.parse(readFileSync(createRequire(join(here, '../package.json')).resolve('turbothemes/themes.json'), 'utf8'));
const need = new Map(); // package -> Set of file names ("400", "700-italic")
for (const s of themes.styles) for (const f of s.fonts ?? []) {
  const set = need.get(f.package) ?? new Set();
  for (const w of f.weights ?? []) set.add(`${w}`);
  for (const w of f.italic ?? []) set.add(`${w}-italic`);
  need.set(f.package, set);
}
// styles whose first font the themes do not list for download (the default look and GTK4): bundle them too
for (const [pkg, files] of Object.entries({ inter: ['400', '500', '600', '700'], cantarell: ['400', '700'] })) need.set(pkg, new Set([...(need.get(pkg) ?? []), ...files]));
const lines = ['/* GENERATED by scripts/gen-fonts.mjs from the fonts turbothemes\' styles ask for: do not edit. Bundled so every style works offline (lib/appearance.ts: fonts: \'none\'). */'];
for (const [pkg, files] of [...need].sort()) for (const f of [...files].sort()) lines.push(`@import '@fontsource/${pkg}/${f}.css';`);
writeFileSync(join(here, '../src/fonts.css'), lines.join('\n') + '\n');
console.log([...need.keys()].sort().map((p) => `@fontsource/${p}`).join(' '));
